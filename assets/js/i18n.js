// ── i18n engine
function setLang(lang) {
  document.documentElement.lang = lang;
  localStorage.setItem('tyr_lang', lang);
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', b.textContent.trim().toLowerCase() === lang));
  const t = translations[lang] || translations['pt'];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) el.placeholder = t[key];
  });
  const titleEl = document.querySelector('title');
  if (titleEl && t['meta.title']) titleEl.textContent = t['meta.title'];
}

(function(){
  const saved = localStorage.getItem('tyr_lang');
  const browser = (navigator.language || navigator.userLanguage || 'pt').toLowerCase();
  let lang = saved || (browser.startsWith('pt') ? 'pt' : browser.startsWith('es') ? 'es' : 'en');
  setLang(lang);
})();
